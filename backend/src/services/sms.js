/**
 * SMS delivery service for OTP handover via MSG91 SendOTP V5 API.
 *
 * Portal remains the single source of truth for OTP validity:
 *   - Portal generates the 6-digit code (src/services/otp.js)
 *   - Portal stores the HMAC-SHA256 hash in otp_challenges
 *   - Portal verifies the code on submission
 *   - MSG91 is only the delivery mechanism; it never verifies the OTP.
 *
 * API contract (MSG91 SendOTP V5):
 *   POST https://control.msg91.com/api/v5/otp
 *   Headers: authkey: <MSG91_AUTH_KEY>, content-type: application/json
 *   Body: { template_id: "<MSG91_OTP_TEMPLATE_ID>", mobile: "<E.164>", otp: "<6-digit>" }
 */

import { HttpError } from '../utils/httpError.js';
import { logger } from '../config/logger.js';

const MSG91_ENDPOINT = 'https://control.msg91.com/api/v5/otp';
const REQUEST_TIMEOUT_MS = 10_000;

/**
 * Send an OTP via MSG91 SendOTP V5 API.
 *
 * @param {object} params
 * @param {string} params.mobile - E.164 formatted mobile number (e.g. +919876543210)
 * @param {string} params.otp - 6-digit numeric OTP generated by Portal
 * @param {string} params.authKey - MSG91 authentication key
 * @param {string} params.templateId - Approved MSG91 OTP template ID
 * @returns {Promise<{ success: boolean, messageId?: string, error?: string }>}
 */
export async function sendOtpSms({ mobile, otp, authKey, templateId }) {
  if (!mobile || typeof mobile !== 'string' || !/^\+[1-9]\d{1,14}$/.test(mobile)) {
    throw new HttpError(400, 'INVALID_PHONE_NUMBER', 'Mobile number must be in E.164 format (e.g. +919876543210).');
  }
  if (!otp || typeof otp !== 'string' || !/^\d{6}$/.test(otp)) {
    throw new HttpError(400, 'INVALID_OTP', 'OTP must be a 6-digit numeric string.');
  }
  if (!authKey || typeof authKey !== 'string' || authKey.length < 8) {
    throw new HttpError(503, 'MSG91_AUTH_KEY_MISSING', 'MSG91 authentication key is not configured.');
  }
  if (!templateId || typeof templateId !== 'string' || templateId.length < 6) {
    throw new HttpError(503, 'MSG91_TEMPLATE_ID_MISSING', 'MSG91 OTP template ID is not configured.');
  }

  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);

  try {
    const response = await fetch(MSG91_ENDPOINT, {
      method: 'POST',
      headers: {
        'content-type': 'application/json',
        authkey: authKey,
      },
      body: JSON.stringify({
        template_id: templateId,
        mobile,
        otp,
      }),
      signal: controller.signal,
    });

    const body = await response.text();
    let parsed;
    try {
      parsed = JSON.parse(body);
    } catch {
      parsed = { raw: body };
    }

    if (!response.ok) {
      // MSG91 returns type=error for business failures (bad auth, bad template, etc.)
      const msg = parsed?.message || parsed?.raw || `HTTP ${response.status}`;
      logger.warn(
        { mobile: maskMobile(mobile), status: response.status, msg },
        'msg91_delivery_failed'
      );
      return {
        success: false,
        error: msg,
      };
    }

    // MSG91 V5 success: type=success, message contains messageId or similar
    const messageId = parsed?.messageId || parsed?.message || parsed?.request_id || undefined;
    logger.info(
      { mobile: maskMobile(mobile), messageId },
      'msg91_delivery_sent'
    );
    return { success: true, messageId };
  } catch (err) {
    if (err.name === 'AbortError') {
      logger.warn({ mobile: maskMobile(mobile) }, 'msg91_delivery_timeout');
      return {
        success: false,
        error: 'PROVIDER_TIMEOUT',
      };
    }
    logger.warn({ mobile: maskMobile(mobile), err: err.message }, 'msg91_delivery_error');
    return {
      success: false,
      error: 'PROVIDER_ERROR',
    };
  } finally {
    clearTimeout(timeoutId);
  }
}

/**
 * Mask an E.164 mobile number for safe logging and responses.
 * Shows the '+' prefix and last 4 digits only; masks everything in between.
 */
export function maskMobile(mobile) {
  if (!mobile || typeof mobile !== 'string') return '';
  const last4 = mobile.length >= 4 ? mobile.slice(-4) : mobile;
  const hasPlus = mobile.startsWith('+');
  const maskedLen = Math.max(0, mobile.length - (hasPlus ? 1 : 0) - last4.length);
  return `${hasPlus ? '+' : ''}${'x'.repeat(maskedLen)}${last4}`;
}

export { MSG91_ENDPOINT };
